def main() -> int:
    apply = "--apply" in sys.argv
    text = README.read_text(encoding="utf-8")
    problems: list[str] = []
    for old, new, why in EDITS:
        count = text.count(old)
        if count != 1:
            problems.append(f"匹配 {count} 次（应为 1）：{why}\n    片段：{old[:60]}…")
            continue
        if apply:
            text = text.replace(old, new, 1)
        print(f"[{'已改' if apply else '待改'}] {why}")
    if problems:
        print("\n!! 以下替换没做成（原文可能已变），请人工确认：")
        for p in problems:
            print("  - " + p)
        return 1
    if apply:
        README.write_text(text, encoding="utf-8")
        print(f"\n已写入 {README}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
